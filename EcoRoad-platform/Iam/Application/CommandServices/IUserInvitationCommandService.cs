using EcoRoad.Iam.Domain.Model.Aggregates;
using EcoRoad.Iam.Domain.Model.Commands;

namespace EcoRoad.Iam.Application.CommandServices;

/// <summary>
/// Application service that handles the commands of the <see cref="UserInvitation" /> aggregate.
/// </summary>
public interface IUserInvitationCommandService
{
    /// <summary>Invites a new collaborator.</summary>
    /// <param name="command">The invitation command.</param>
    /// <param name="cancellationToken">Token used to cancel the operation.</param>
    /// <returns>The pending invitation.</returns>
    Task<UserInvitation> Handle(InviteUserCommand command, CancellationToken cancellationToken = default);

    /// <summary>Accepts an invitation and creates the user account with pending access.</summary>
    /// <param name="command">The acceptance command.</param>
    /// <param name="cancellationToken">Token used to cancel the operation.</param>
    /// <returns>The user generated by the invitation.</returns>
    Task<User> Handle(AcceptInvitationCommand command, CancellationToken cancellationToken = default);
}
